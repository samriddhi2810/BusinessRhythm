CREATE TABLE IF NOT EXISTS products (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 price DECIMAL(12,2) NOT NULL CHECK(price >= 0),
 stock INT NOT NULL CHECK(stock >= 0),
 minimum_stock INT NOT NULL CHECK(minimum_stock >= 0),
 active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, contact VARCHAR(160) NOT NULL
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, customer_id BIGINT NOT NULL,
 order_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(20) NOT NULL DEFAULT 'Pending', total DECIMAL(14,2) NOT NULL,
 FOREIGN KEY(customer_id) REFERENCES customers(id)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT AUTO_INCREMENT PRIMARY KEY, order_id BIGINT NOT NULL, product_id BIGINT NOT NULL,
 quantity INT NOT NULL CHECK(quantity > 0), unit_price DECIMAL(12,2) NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(product_id) REFERENCES products(id),
 UNIQUE(order_id, product_id)
);
